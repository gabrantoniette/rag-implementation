const QuestionSchema = z.object({
  id: z.string(),
  question: z.string(),
  capability: z.string(),
  expected_facts: z.array(
    z.object({
      fact: z.string(),
      article: z.string(),
      section: z.string(),
      /** Words that must all appear in the answer (case-insensitive) for the fact to count. */
      match: z.array(z.string()).min(1),
    }),
  ),
  must_refuse: z.boolean(),
});
type Question = z.infer<typeof QuestionSchema>;

const date = () => new Date().toISOString().slice(0, 10);
const write = (name: string, content: string) => {
  mkdirSync(PATHS.evidence, { recursive: true });
  writeFileSync(path.join(PATHS.evidence, name), content);
  return `docs/evidence/${name}`;
};

/** Expected article (and section prefix) present in the selected context. */
function sourceRetrieved(state: ChainState, q: Question): boolean[] {
  return q.expected_facts.map((f) =>
    state.context.some(
      (c) =>
        c.chunk.documentTitle === f.article &&
        (c.chunk.section === f.section || c.chunk.section.startsWith(`${f.section} >`)),
    ),
  );
}

async function retrievalOnly(rag: RagInstance, questions: Question[]) {
  const sections: string[] = [`# Retrieval-only evidence (${date()})`, ''];
  sections.push(
    'Generated by `npm run evidence` without OPENROUTER_API_KEY: retrieval, graph expansion, reranking, context selection',
    'and the evidence gate run for real; no LLM is called. Live answers come from stage B.',
    '',
  );
  const json = [];
  for (const q of questions) {
    const result = await rag.ask(q.question, { mode: 'full', retrievalOnly: true });
    const found = sourceRetrieved(result.state, q);
    sections.push(
      `## ${q.id}: ${q.question}`,
      '',
      `Capability: ${q.capability}. Must refuse: ${q.must_refuse}.`,
      '',
    );
    q.expected_facts.forEach((f, i) =>
      sections.push(
        `- Expected fact: ${f.fact} (${f.article} > ${f.section}) - source in context: ${found[i] ? 'yes' : 'NO'}`,
      ),
    );
    const gate = result.state.gate!;
    sections.push(
      `- Evidence gate: best reranker score ${gate.bestScore.toFixed(4)} vs threshold ${gate.threshold.toFixed(4)} -> ${gate.passed ? 'would call the LLM' : 'would REFUSE without calling the LLM'}`,
      '',
      '```text',
      describeRetrieval(result.state, 8),
      '```',
      '',
    );
    json.push({ ...q, sourceInContext: found, state: serializableState(result.state) });
  }
  return {
    md: write(`retrieval-only-${date()}.md`, sections.join('\n')),
    json: write(`retrieval-only-${date()}.json`, `${JSON.stringify(json, null, 2)}\n`),
  };
}

async function live(rag: RagInstance, questions: Question[]) {
  const sections: string[] = [
    `# Live evidence (${date()})`,
    '',
    'Generated by `npm run evidence` with OPENROUTER_API_KEY set (cache bypassed).',
    '',
  ];
  const json = [];
  for (const q of questions) {
    const start = performance.now();
    const result = await rag.ask(q.question, { mode: 'full', bypassCache: true });
    const latencyMs = Math.round(performance.now() - start);
    const s = result.state;
    const v = s.verification;
    const answer = (s.rawAnswer ?? s.answer ?? '').toLowerCase();
    const facts = q.expected_facts.map((f) =>
      f.match.every((m) => answer.includes(m.toLowerCase())),
    );
    const criteria = q.must_refuse
      ? { refused: result.refused }
      : {
          atLeastOneCitation: s.citations.length >= 1,
          allCitationsExist: !!v && v.invalidCitations.length === 0,
          grounding80:
            !!v && v.groundingScore >= rag.config.parameters.verification.groundingPassThreshold,
          expectedFacts: facts.every(Boolean),
        };
    const pass = Object.values(criteria).every(Boolean);
    sections.push(
      `## ${q.id}: ${q.question} - ${pass ? 'PASS' : 'FAIL'}`,
      '',
      `Capability: ${q.capability}. Intent: ${s.intent} (${s.intentSource}). Model: ${s.model ?? '(none: refused before the LLM)'}. Latency: ${latencyMs} ms. Tokens: ${s.usage?.totalTokens ?? 'not reported'}.`,
      '',
      '| Criterion | Result |',
      '| --- | --- |',
      ...Object.entries(criteria).map(([k, ok]) => `| ${k} | ${ok ? 'pass' : 'FAIL'} |`),
      '',
      '### Answer',
      '',
      result.answer,
      '',
      `Grounding score: ${v ? v.groundingScore.toFixed(2) : '-'}; unsupported sentences: ${v ? v.sentences.filter((x) => !x.supported).length : '-'}`,
      ...(v?.sentences
        .filter((x) => !x.supported)
        .map((x) => `- unsupported (${x.support.toFixed(3)}): ${x.sentence}`) ?? []),
      '',
      '### Retrieval',
      '',
      '```text',
      s.context.map(candidateLine).join('\n'),
      '',
      graphPaths(s).slice(0, 10).join('\n') || '(no graph expansion in context)',
      '```',
      '',
    );
    json.push({
      ...q,
      pass,
      criteria,
      factsFound: facts,
      latencyMs,
      answer: result.answer,
      state: serializableState(s),
    });
  }
  return {
    md: write(`live-${date()}.md`, sections.join('\n')),
    json: write(`live-${date()}.json`, `${JSON.stringify(json, null, 2)}\n`),
    passed: json.filter((j) => j.pass).length,
  };
}

const OCR_FORMATS = new Set(['pdf (OCR)', 'png', 'jpg', 'webp', 'bmp']);
const goldFound = (text: string, gold: string, format: string) => {
  if (text.includes(gold)) return true;
  if (!OCR_FORMATS.has(format)) return false;
  const have = new Set(contentTerms(text));
  const want = contentTerms(gold);
  return want.filter((w) => have.has(w)).length / want.length >= 0.8;
};

async function formatSmoke(rag: RagInstance) {
  const dir = path.join(PATHS.cache, 'format-fixtures');
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const fixtures = await writeFormatFixtures(dir);
  const rows: string[] = [];
  let failures = 0;
  for (const fx of fixtures) {
    await rag.documents.upsert({ source: { path: fx.file }, collection: 'fixtures' });
    const result = await rag.ask(fx.query, {
      mode: 'full',
      retrievalOnly: true,
      collection: 'fixtures',
    });
    const top = result.state.ranked.slice(0, 4);
    const rank = top.findIndex((c) => goldFound(c.chunk.text, fx.gold, fx.format));
    const hit = rank >= 0 ? top[rank]! : null;
    const locator = hit ? formatLocator(hit.chunk.locator, hit.chunk.documentFormat) : '-';
    const ok = !!hit && locator === fx.locator;
    if (!ok) failures++;
    rows.push(
      `| ${fx.format} | ${path.basename(fx.file)} | ${fx.query} | ${rank >= 0 ? rank + 1 : 'not in top 4'} | ${locator} | ${ok ? 'PASS' : 'FAIL'} |`,
    );
  }
  const ffmpeg = findFfmpeg(rag.config.env.FFMPEG_PATH);
  const md = [
    `# Format smoke run (${date()})`,
    '',
    'Generated by `npm run evidence -- --formats`: each fixture is generated at run time (never downloaded), ingested',
    "into the 'fixtures' collection with the real loaders, embedder, OCR and Neo4j, then queried retrieval-only.",
    'PASS = the gold chunk is in the top 4 and its rendered locator matches.',
    `Neo4j: ${rag.config.env.NEO4J_URI}.`,
    '',
    '| Format | File | Query | Gold rank | Locator | Result |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
    'Image captioner: Florence-2 with ViT-GPT2 fallback (loaded on first image). Captions are model-generated and never asserted.',
    ffmpeg
      ? `ffmpeg: found (${ffmpeg}). Audio/video transcription and keyframe analysis are covered by the unit tests that require ffmpeg.`
      : 'ffmpeg: NOT FOUND. Audio and video transcription (Whisper) and video keyframe analysis are UNVERIFIED on this machine; only the sidecar-subtitle path ran.',
    '',
  ].join('\n');
  return { md: write(`formats-${date()}.md`, md), failures, total: fixtures.length };
}

/**
 * npm run evidence [-- --formats]
 * Without OPENROUTER_API_KEY: retrieval-only evidence for the five questions (exit 0) and the key
 * instructions. With the key: one live LLM call per question (cache bypassed) and pass/fail per
 * criterion. --formats: the format smoke run over generated fixtures.
 */
runCli(async () => {
  const args = parseArgs(process.argv.slice(2), ['formats']);
  const probe = await createRag({ llm: 'none' });
  const hasKey = probe.config.env.OPENROUTER_API_KEY.length > 0;
  await probe.close();
  if (args.flags.formats) {
    const rag = await createRag({ llm: 'none' });
    try {
      const r = await formatSmoke(rag);
      process.stdout.write(
        `Format smoke: ${r.total - r.failures}/${r.total} PASS. Report: ${r.md}\n`,
      );
      return r.failures > 0 ? 1 : 0;
    } finally {
      await rag.close();
    }
  }
  const file = path.join(probe.config.domain.evalDir, 'questions.json');
  if (!existsSync(file)) throw new Error(`Missing ${file}`);
  const questions = z.array(QuestionSchema).parse(JSON.parse(readFileSync(file, 'utf8')));
  const rag = await createRag(hasKey ? {} : { llm: 'none' });
  try {
    if (!hasKey) {
      const r = await retrievalOnly(rag, questions);
      process.stdout.write(
        [
          `Retrieval-only evidence written: ${r.md} and ${r.json}`,
          '',
          'OPENROUTER_API_KEY is not set, so no LLM was called. To run the live evidence (stage B):',
          '  1. Create a key at https://openrouter.ai/keys (free models only are ever used).',
          '  2. Put it in .env:  OPENROUTER_API_KEY=<your key>',
          '  3. npm run db:up   (if Neo4j is not running)',
          '  4. npm run evidence',
          '',
        ].join('\n'),
      );
      return 0;
    }
    const r = await live(rag, questions);
    process.stdout.write(
      `Live evidence: ${r.passed}/${questions.length} PASS. Reports: ${r.md} and ${r.json}\n`,
    );
    return 0;
  } finally {
    await rag.close();
  }
});
