import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { Mode } from '../core/chain.js';
import {
  type ModeMetrics,
  chunkIndex,
  evaluateMode,
  loadEvalSet,
  syntheticSplit,
} from '../core/evaluation.js';
import { PATHS } from '../core/paths.js';
import type { RetrievalDeps } from '../core/pipeline.js';
import { createRag } from '../index.js';
import { runCli } from './args.js';

const ROWS: [Mode, string][] = [
  ['vector', 'vector only'],
  ['hybrid', 'hybrid (vector + fulltext, RRF)'],
  ['graph', 'hybrid + graph expansion'],
  ['rerank', 'hybrid + graph + reranker'],
];

const START = '<!-- ablation:start -->';
const END = '<!-- ablation:end -->';

function table(title: string, results: [string, ModeMetrics][]): string {
  const f = (n: number) => n.toFixed(3);
  return [
    `**${title}** (${results[0]?.[1].queries ?? 0} queries)`,
    '',
    '| Pipeline | recall@6 | MRR | nDCG@6 |',
    '| --- | --- | --- | --- |',
    ...results.map(
      ([label, m]) => `| ${label} | ${f(m.recallAt6)} | ${f(m.mrr)} | ${f(m.ndcgAt6)} |`,
    ),
  ].join('\n');
}

/**
 * npm run eval:retrieval: the ablation table (recall@6, MRR, nDCG@6) for vector, hybrid,
 * hybrid + graph and hybrid + graph + reranker, on the hand-written eval set and on the synthetic
 * validation set, reported separately. Writes docs/evaluation.md (ablation block) and a JSON copy.
 */
runCli(async () => {
  const rag = await createRag({ llm: 'none' });
  try {
    const deps: RetrievalDeps = { ...rag, parameters: rag.config.parameters };
    const collection = rag.config.domain.collection;
    const index = await chunkIndex(deps, collection);
    const hand = loadEvalSet(path.join(rag.config.domain.evalDir, 'retrieval-eval.json'));
    const { val } = syntheticSplit(index);
    const results: Record<string, [string, ModeMetrics][]> = { hand: [], synthetic: [] };
    const perQuery: Record<string, unknown> = {};
    for (const [mode, label] of ROWS) {
      const h = await evaluateMode(hand, mode, deps, index, collection);
      const s = await evaluateMode(val, mode, deps, index, collection);
      results.hand!.push([label, h]);
      results.synthetic!.push([label, s]);
      perQuery[mode] = { hand: h.perQuery, synthetic: s.perQuery };
      process.stdout.write(
        `${mode}: hand nDCG@6=${h.ndcgAt6.toFixed(3)} synthetic nDCG@6=${s.ndcgAt6.toFixed(3)}\n`,
      );
    }
    const date = new Date().toISOString().slice(0, 10);
    const block = [
      START,
      `Generated by \`npm run eval:retrieval\` on ${date}. Reranker: ${rag.reranker.name}. Collection: ${collection}.`,
      '',
      table('Hand-written eval set (domains/eval/retrieval-eval.json)', results.hand!),
      '',
      table('Synthetic validation set (section headings as pseudo-queries)', results.synthetic!),
      '',
      'Only the hand-written set supports claims about whether a stage helps; the synthetic queries',
      'reuse section headings, which favours keyword and title features.',
      END,
    ].join('\n');
    const file = path.join(PATHS.docs, 'evaluation.md');
    const current = existsSync(file)
      ? readFileSync(file, 'utf8')
      : '# Evaluation\n\n## Retrieval ablation\n\n' + `${START}\n${END}\n`;
    const next = current.includes(START)
      ? current.slice(0, current.indexOf(START)) +
        block +
        current.slice(current.indexOf(END) + END.length)
      : `${current.trimEnd()}\n\n## Retrieval ablation\n\n${block}\n`;
    // docs/ is checked by `prettier --check` (npm run lint): write the file already formatted.
    const prettier = await import('prettier');
    const options = (await prettier.resolveConfig(file)) ?? {};
    writeFileSync(file, await prettier.format(next, { ...options, filepath: file }));
    mkdirSync(PATHS.evidence, { recursive: true });
    writeFileSync(
      path.join(PATHS.evidence, `ablation-${date}.json`),
      `${JSON.stringify({ date, reranker: rag.reranker.name, results, perQuery }, null, 2)}\n`,
    );
    process.stdout.write(`\n${block}\n`);
    return 0;
  } finally {
    await rag.close();
  }
});
