import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { PATHS } from '../core/paths.js';
import type { ScenarioResult, Thresholds } from './types.js';

export interface ReportMeta {
  date: string;
  live: boolean;
  commit: string;
  thresholds?: Thresholds;
  /** Free text for the report (for example a recalibration note). */
  notes?: string[];
}

const verdict = (r: ScenarioResult) => (!r.covered ? 'NOT COVERED' : r.pass ? 'PASS' : 'FAIL');

function markdown(results: ScenarioResult[], meta: ReportMeta): string {
  const lines = [
    `# MCP evaluation (${meta.date})`,
    '',
    `Generated by \`npm run mcp:eval${meta.live ? ' -- --live' : ''}\` at commit \`${meta.commit}\`. ` +
      (meta.live
        ? 'Live mode: at most one OpenRouter request.'
        : 'Answers came from the mock LLM: no OpenRouter request was made.'),
    '',
    '| Scenario | Result |',
    '| --- | --- |',
    ...results.map((r) => `| ${r.name} | ${verdict(r)} |`),
    '',
  ];
  for (const r of results) {
    lines.push(`## ${r.name}: ${verdict(r)}`, '');
    if (r.measures.length) {
      lines.push('| Measure | Value | Limit | Result |', '| --- | --- | --- | --- |');
      for (const m of r.measures)
        lines.push(
          `| ${m.name} | ${m.value} ${m.unit} | ${m.limit ?? '-'} | ${m.pass === undefined ? '-' : m.pass ? 'pass' : 'FAIL'} |`,
        );
      lines.push('');
    }
    lines.push('Findings:', '');
    lines.push(...(r.findings.length ? r.findings.map((f) => `- ${f}`) : ['- none']), '');
    if (r.notes.length) lines.push('Notes:', '', ...r.notes.map((n) => `- ${n}`), '');
  }
  if (meta.notes?.length) lines.push('## Run notes', '', ...meta.notes.map((n) => `- ${n}`), '');
  return `${lines.join('\n')}\n`;
}

/** Writes docs/evidence/mcp-<date>.json and .md, already formatted by Prettier. */
export async function writeReport(
  results: ScenarioResult[],
  meta: ReportMeta,
): Promise<{ json: string; md: string }> {
  mkdirSync(PATHS.evidence, { recursive: true });
  const json = path.join(PATHS.evidence, `mcp-${meta.date}.json`);
  const md = path.join(PATHS.evidence, `mcp-${meta.date}.md`);
  const prettier = await import('prettier');
  const format = async (file: string, text: string) =>
    prettier.format(text, { ...((await prettier.resolveConfig(file)) ?? {}), filepath: file });
  writeFileSync(json, await format(json, JSON.stringify({ ...meta, results }, null, 2)));
  writeFileSync(md, await format(md, markdown(results, meta)));
  return { json, md };
}
